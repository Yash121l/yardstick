export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Rows of booleans for one character, or the blank glyph if unknown. */
export function glyph(ch: string): boolean[][] {
  const key = ch.toUpperCase();
  const spec = GLYPHS[key] ?? GLYPHS[" "];
  return (spec as string).split("|").map((row) => [...row].map((c) => c === "#"));
}

/** Characters this font can actually draw. Anything else renders blank. */
export function isRenderable(ch: string): boolean {
  return GLYPHS[ch.toUpperCase()] !== undefined;
}

export function unrenderable(text: string): string[] {
  return [...new Set([...text].filter((c) => !isRenderable(c)))];
}
